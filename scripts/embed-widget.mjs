import { mkdirSync, readFileSync, writeFileSync } from "node:fs"

// Inline the built widget into a TS module so the serverless bundle needs no
// filesystem access at runtime.
const html = readFileSync(new URL("../dist/widget/index.html", import.meta.url), "utf8")
mkdirSync(new URL("../src/generated/", import.meta.url), { recursive: true })
writeFileSync(
  new URL("../src/generated/widget-html.ts", import.meta.url),
  `// Generated by scripts/embed-widget.mjs — do not edit.\nexport const WIDGET_HTML = ${JSON.stringify(html)}\n`,
)
console.log(`embedded widget (${(html.length / 1024).toFixed(1)} KB)`)
