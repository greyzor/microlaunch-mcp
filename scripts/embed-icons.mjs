import { mkdirSync, readFileSync, writeFileSync } from "node:fs"

// Inline the listing icons (submission/assets) so the worker can serve them:
// MCP clients (ChatGPT dev apps, Claude) take the app icon from serverInfo.icons
// or the site favicon, not from the plugin zip.
const b64 = (f) => readFileSync(new URL(`../submission/assets/${f}`, import.meta.url)).toString("base64")
mkdirSync(new URL("../src/generated/", import.meta.url), { recursive: true })
writeFileSync(
  new URL("../src/generated/icons.ts", import.meta.url),
  `// Generated by scripts/embed-icons.mjs — do not edit.\nexport const ICON_PNG_B64 = ${JSON.stringify(b64("icon.png"))}\nexport const LOGO_PNG_B64 = ${JSON.stringify(b64("logo.png"))}\n`,
)
console.log("embedded icons")
